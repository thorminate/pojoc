//! TypeScript codecs over the same resolved layouts as the Rust target.

use super::{ordered_wire_fields, version_uses_intern};
use crate::core::types::{ResolvedTypeRef, TypeId, is_primitive, normalize_type};
use crate::schema::ir::ir_types::{
    DefaultValue, FieldIR, ResolvedConst, ResolvedSchema, latest_by_name,
};
use crate::schema::ir::lineage::FieldMapping;
use serde_json::{Value, json};
use std::collections::BTreeMap;
use std::fmt::Write;

const RUNTIME: &str = include_str!("typescript_runtime.ts");
const NPM_RUNTIME: &str = "import { makeCodec, type SchemaSpec } from \"pojoc/v1\";";

/// Generate a TypeScript module that imports the versioned npm runtime API.
pub fn generate(schema: &ResolvedSchema) -> Result<String, Error> {
    generate_module(schema, "", NPM_RUNTIME)
}

/// Generate a self-contained TypeScript module with no package dependencies.
pub fn generate_standalone(schema: &ResolvedSchema) -> Result<String, Error> {
    generate_module(schema, " --standalone", RUNTIME)
}

fn generate_module(schema: &ResolvedSchema, options: &str, runtime: &str) -> Result<String, Error> {
    let mut schemas = Vec::new();
    collect_schemas(schema, &mut schemas);
    let root = schemas.len() - 1;
    let mut out = format!("// @generated by pojoc --target typescript{options}\n{runtime}\n");
    for (scope, schema) in schemas.iter().enumerate() {
        emit_types(&mut out, &schemas, scope, schema, scope == root);
    }
    let plans = schemas
        .iter()
        .map(|schema| schema_plan(schema, &schemas))
        .collect::<Result<Vec<_>, _>>()?;
    writeln!(out, "const __schemas: SchemaSpec[] = {};", json!(plans)).unwrap();
    let root_type = type_name(root, &schema.name_hint);
    writeln!(
        out,
        "const codec = makeCodec<{root_type}>(__schemas, {root});\n\
         export const {{ version, encode, encodeForVersion, decode, decodeFrom, create, seek }} = codec;"
    )
    .unwrap();
    Ok(out)
}

#[derive(Debug, thiserror::Error)]
pub enum Error {
    #[error("schema version {0} cannot be represented in the envelope's u64 version")]
    Version(i128),
}

fn collect_schemas<'a>(schema: &'a ResolvedSchema, schemas: &mut Vec<&'a ResolvedSchema>) {
    if schemas.iter().any(|other| std::ptr::eq(*other, schema)) {
        return;
    }
    let imports: BTreeMap<_, _> = schema.imports.iter().collect();
    for child in imports.values() {
        collect_schemas(child, schemas);
    }
    schemas.push(schema);
}

fn scope_of(schemas: &[&ResolvedSchema], schema: &ResolvedSchema) -> usize {
    schemas
        .iter()
        .position(|other| std::ptr::eq(*other, schema))
        .unwrap()
}

fn type_name(scope: usize, name: &str) -> String {
    format!("__S{scope}_{name}")
}

fn id_key(id: &TypeId) -> String {
    format!("{}@{}", id.name, id.version)
}

fn newest_id<'a, T>(items: &'a std::collections::HashMap<TypeId, T>, id: &'a TypeId) -> &'a TypeId {
    items
        .keys()
        .filter(|key| key.name == id.name)
        .max_by_key(|key| key.version)
        .unwrap_or(id)
}

fn array_type(ty: &ResolvedTypeRef) -> Option<&'static str> {
    let ResolvedTypeRef::Scalar(id) = ty else {
        return None;
    };
    Some(match normalize_type(&id.name) {
        "u8" => "Uint8Array",
        "i8" => "Int8Array",
        "u16" => "Uint16Array",
        "i16" => "Int16Array",
        "u32" => "Uint32Array",
        "i32" => "Int32Array",
        "u64" => "BigUint64Array",
        "i64" => "BigInt64Array",
        "f32" => "Float32Array",
        "f64" => "Float64Array",
        _ => return None,
    })
}

fn type_expr(ty: &ResolvedTypeRef, schemas: &[&ResolvedSchema], scope: usize) -> String {
    use ResolvedTypeRef::*;
    let child = |ty| type_expr(ty, schemas, scope);
    match ty {
        Scalar(id) if is_primitive(&id.name) => match normalize_type(&id.name) {
            "string" => "string",
            "bool" => "boolean",
            "u64" | "i64" | "varint64" => "bigint",
            _ => "number",
        }
        .into(),
        Scalar(id) | Enum(id, _) | Bitset(id, _) | Union(id) => type_name(scope, &id.name),
        ImportedSchema {
            alias, root_name, ..
        } => type_name(scope_of(schemas, &schemas[scope].imports[alias]), root_name),
        Array(inner) | FixedArray(inner, _) | DeltaArray(inner) | FixedDeltaArray(inner, _) => {
            array_type(inner)
                .map(str::to_owned)
                .unwrap_or_else(|| format!("Array<{}>", child(inner)))
        }
        Map(key, value) => format!("Map<{}, {}>", child(key), child(value)),
        FixedMap(key, value, _) => format!("Array<[{}, {}]>", child(key), child(value)),
        Tuple(items) => format!(
            "[{}]",
            items.iter().map(child).collect::<Vec<_>>().join(", ")
        ),
        Optional(inner) => format!("({} | null)", child(inner)),
        Boxed(inner) | Constrained { inner, .. } => child(inner),
        Interned(_) => "string".into(),
        FixedString(_) => "Uint8Array".into(),
        VFloat { .. } => "number".into(),
    }
}

fn declarations(
    out: &mut String,
    schemas: &[&ResolvedSchema],
    scope: usize,
    name: &str,
    fields: &[FieldIR],
) {
    writeln!(out, "interface {} {{", type_name(scope, name)).unwrap();
    for field in fields {
        writeln!(
            out,
            "  {}: {};",
            json!(field.name),
            type_expr(&field.ty, schemas, scope)
        )
        .unwrap();
    }
    out.push_str("}\n");
}

fn emit_constants(out: &mut String, internal: &str, name: &str, constants: &[ResolvedConst]) {
    if constants.is_empty() {
        return;
    }
    writeln!(out, "const {internal} = {{").unwrap();
    for constant in constants {
        let value = match &constant.value {
            DefaultValue::Int(n) if matches!(constant.rust_type, "u64" | "i64") => format!("{n}n"),
            DefaultValue::Int(n) => n.to_string(),
            DefaultValue::Float(n) if constant.rust_type == "f32" => format!("Math.fround({n})"),
            DefaultValue::Float(n) => n.to_string(),
            DefaultValue::Bool(value) => value.to_string(),
            DefaultValue::Str(value) => json!(value).to_string(),
            _ => unreachable!("the analyzer only accepts scalar constants"),
        };
        writeln!(out, "  [{}]: {value},", json!(constant.name)).unwrap();
    }
    writeln!(out, "}} as const;\nexport {{ {internal} as {name} }};").unwrap();
}

fn emit_types(
    out: &mut String,
    schemas: &[&ResolvedSchema],
    scope: usize,
    schema: &ResolvedSchema,
    public: bool,
) {
    let records: BTreeMap<_, _> = latest_by_name(&schema.types.types).into_iter().collect();
    let enums: BTreeMap<_, _> = latest_by_name(&schema.enums.enums).into_iter().collect();
    let unions: BTreeMap<_, _> = latest_by_name(&schema.unions.unions).into_iter().collect();
    let bitsets: BTreeMap<_, _> = latest_by_name(&schema.bitsets.bitsets)
        .into_iter()
        .collect();
    let export_type = |out: &mut String, name: &str| {
        if public {
            writeln!(
                out,
                "export type {{ {} as {name} }};",
                type_name(scope, name)
            )
            .unwrap();
        }
    };
    declarations(
        out,
        schemas,
        scope,
        &schema.name_hint,
        &schema.versions.last().unwrap().fields,
    );
    export_type(out, &schema.name_hint);
    if public {
        emit_constants(
            out,
            "__rootConstants",
            "constants",
            &schema.versions.last().unwrap().const_fields,
        );
    }
    for (name, (_, record)) in records {
        declarations(out, schemas, scope, &name, &record.fields);
        export_type(out, &name);
        if public {
            emit_constants(
                out,
                &format!("__C{scope}_{name}"),
                &format!("{name}Constants"),
                &record.const_fields,
            );
        }
    }
    for (name, (_, en)) in enums {
        let internal = type_name(scope, &name);
        let mut values = BTreeMap::from([("Unknown", 0)]);
        values.extend(en.variants.iter().map(|v| (v.name.as_str(), v.wire_value)));
        let mut discriminants: Vec<_> = values.values().copied().collect();
        discriminants.sort_unstable();
        discriminants.dedup();
        let ty = discriminants
            .iter()
            .map(u32::to_string)
            .collect::<Vec<_>>()
            .join(" | ");
        if public {
            writeln!(
                out,
                "const {internal} = {} as const;\nexport {{ {internal} as {name} }};",
                json!(values)
            )
            .unwrap();
        }
        writeln!(out, "type {internal} = {ty};").unwrap();
    }
    for (name, (_, bs)) in bitsets {
        writeln!(out, "type {} = Uint8Array;", type_name(scope, &name)).unwrap();
        export_type(out, &name);
        if public {
            let values: BTreeMap<_, _> = bs
                .variants
                .iter()
                .enumerate()
                .map(|(i, v)| (&v.name, i))
                .collect();
            writeln!(out, "const __B{scope}_{name} = {} as const;\nexport {{ __B{scope}_{name} as {name}Bits }};", json!(values)).unwrap();
        }
    }
    for (name, (_, union)) in unions {
        writeln!(
            out,
            "type {} = {{ kind: \"Unknown\"; discriminant: number; data: Uint8Array }}",
            type_name(scope, &name)
        )
        .unwrap();
        for variant in &union.variants {
            writeln!(
                out,
                "  | {{ kind: {}; value: {} }}",
                json!(variant.name),
                type_expr(&variant.payload, schemas, scope)
            )
            .unwrap();
        }
        out.push_str(";\n");
        export_type(out, &name);
    }
}

fn default_plan(value: &DefaultValue, schema: &ResolvedSchema) -> Value {
    let child = |value| default_plan(value, schema);
    match value {
        DefaultValue::None | DefaultValue::Struct => Value::Null,
        DefaultValue::Bool(value) => json!(value),
        DefaultValue::Int(value) => json!(["integer", value.to_string()]),
        DefaultValue::Float(value) => json!(value),
        DefaultValue::Str(value) => json!(value),
        DefaultValue::Array(items) | DefaultValue::Tuple(items) => {
            json!(["items", items.iter().map(child).collect::<Vec<_>>()])
        }
        DefaultValue::Map(items) => {
            json!([
                "pairs",
                items
                    .iter()
                    .map(|(key, value)| [child(key), child(value)])
                    .collect::<Vec<_>>()
            ])
        }
        DefaultValue::FixedBytes(bytes) => json!(["bytes", bytes]),
        DefaultValue::Repeat(value) => json!(["repeat", child(value)]),
        DefaultValue::EnumVariant { ty_name, variant } => {
            let latest = latest_by_name(&schema.enums.enums);
            let code = latest
                .get(ty_name)
                .and_then(|(_, en)| en.variants.iter().find(|v| v.name == *variant))
                .map_or(0, |v| v.wire_value);
            json!(code)
        }
        DefaultValue::BitsetLiteral { ty_name, kvs } => {
            let latest = latest_by_name(&schema.bitsets.bitsets);
            let mut bytes = Vec::new();
            if let Some((_, bitset)) = latest.get(ty_name) {
                bytes.resize(bitset.byte_width(), 0);
                for (name, enabled) in kvs {
                    if *enabled
                        && let Some(bit) = bitset.variants.iter().position(|v| v.name == *name)
                    {
                        bytes[bit / 8] |= 1u8 << (bit % 8);
                    }
                }
            }
            json!(["bytes", bytes])
        }
    }
}

fn descriptor(ty: &ResolvedTypeRef, schema: &ResolvedSchema) -> Value {
    use ResolvedTypeRef::*;
    let child = |ty| descriptor(ty, schema);
    match ty {
        Scalar(id) if is_primitive(&id.name) => json!(normalize_type(&id.name)),
        Scalar(id) => json!([
            "record",
            id_key(id),
            id_key(newest_id(&schema.types.types, id))
        ]),
        Enum(id, width) => {
            let latest = &schema.enums.enums[newest_id(&schema.enums.enums, id)];
            let historical = &schema.enums.enums[id];
            let values: Vec<_> = latest.variants.iter().map(|v| v.wire_value).collect();
            let max = historical
                .variants
                .iter()
                .map(|v| v.wire_value)
                .max()
                .unwrap_or(0);
            json!(["enum", width, values, max])
        }
        Bitset(id, width) => {
            let latest = &schema.bitsets.bitsets[newest_id(&schema.bitsets.bitsets, id)];
            json!(["bits", width, latest.byte_width()])
        }
        Union(id) => {
            let latest = &schema.unions.unions[newest_id(&schema.unions.unions, id)];
            let historical = &schema.unions.unions[id];
            let variants = |source: &crate::schema::ir::ir_types::ResolvedUnion| {
                source
                    .variants
                    .iter()
                    .map(|v| {
                        let name = latest
                            .variants
                            .iter()
                            .find(|latest| latest.discriminant == v.discriminant)
                            .map_or(v.name.as_str(), |latest| &latest.name);
                        json!([v.discriminant, name, descriptor(&v.payload, schema)])
                    })
                    .collect::<Vec<_>>()
            };
            json!([
                "union",
                historical.discriminant_width(),
                variants(historical),
                variants(latest)
            ])
        }
        Array(inner) => json!(["array", child(inner), null]),
        FixedArray(inner, count) => json!(["array", child(inner), count]),
        DeltaArray(inner) => json!(["delta", child(inner), null]),
        FixedDeltaArray(inner, count) => json!(["delta", child(inner), count]),
        FixedString(count) => json!(["bytes", count]),
        Map(key, value) => json!(["map", child(key), child(value), null]),
        FixedMap(key, value, count) => json!(["map", child(key), child(value), count]),
        Tuple(items) => json!(["tuple", items.iter().map(child).collect::<Vec<_>>()]),
        VFloat {
            min, step, backing, ..
        } => json!(["vfloat", min, step, backing.wire_size()]),
        Optional(inner) => json!(["optional", child(inner)]),
        Boxed(inner) => json!(["box", child(inner)]),
        Constrained { inner, min, max } => json!(["constraint", child(inner), min, max]),
        Interned(_) => json!("intern"),
        ImportedSchema { alias, version, .. } => json!(["import", alias, version.to_string()]),
    }
}

fn field_plan(field: &FieldIR, schema: &ResolvedSchema, cast: bool) -> Value {
    json!({
        "id": field.id.0.to_string(),
        "name": field.name,
        "ty": descriptor(&field.ty, schema),
        "default": field.default.as_ref().map(|value| default_plan(value, schema)),
        "seek": field.seekable,
        "lazy": field.lazy,
        "cast": cast,
    })
}

fn schema_plan(schema: &ResolvedSchema, schemas: &[&ResolvedSchema]) -> Result<Value, Error> {
    let records: BTreeMap<_, _> = schema
        .types
        .types
        .iter()
        .map(|(key, record)| {
            (
                id_key(key),
                record
                    .fields
                    .iter()
                    .map(|field| field_plan(field, schema, false))
                    .collect::<Vec<_>>(),
            )
        })
        .collect();
    let imports: BTreeMap<_, _> = schema
        .imports
        .iter()
        .map(|(alias, child)| (alias, scope_of(schemas, child)))
        .collect();
    let mut roots = BTreeMap::new();
    for (resolved, version) in schema.versions.iter().zip(&schema.lineage.versions) {
        let number = u64::try_from(version.version).map_err(|_| Error::Version(version.version))?;
        let fields: Vec<_> = ordered_wire_fields(version)
            .into_iter()
            .map(|field| {
                let source = resolved
                    .fields
                    .iter()
                    .find(|src| src.id == field.field_id)
                    .unwrap();
                field_plan(
                    source,
                    schema,
                    matches!(field.mapping, FieldMapping::Cast { .. }),
                )
            })
            .collect();
        roots.insert(
            number.to_string(),
            json!({"fields": fields, "intern": version_uses_intern(schema, &version.fields)}),
        );
    }
    Ok(
        json!({ "latest": schema.lineage.latest_version.to_string(), "roots": roots, "records": records, "imports": imports }),
    )
}
