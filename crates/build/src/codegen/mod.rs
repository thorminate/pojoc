// wire byte size if ty is fixed-width, none if variable
pub(crate) fn wire_fixed_size(ty: &ResolvedTypeRef) -> Option<usize> {
    match type_info(ty).wire_size {
        WireSize::Fixed(n) => Some(n),
        WireSize::Variable => None,
    }
}

fn target_is_lazy(schema: &ResolvedSchema, target_name: &str) -> bool {
    schema
        .versions
        .last()
        .unwrap()
        .fields
        .iter()
        .find(|f| f.name == *target_name)
        .map(|f| f.lazy)
        .unwrap_or(false)
}

// A version's layout uses its own field types and modifiers, even when a
// newer schema reads those fields through a cast or a lazy view.
pub(crate) fn is_fixed_wire_field(fl: &FieldLineage) -> bool {
    !fl.lazy
        && wire_fixed_size(&fl.source_ty).is_some()
        && !contains_fixed_map(&fl.source_ty)
        && !contains_enum_under_closure(&fl.source_ty)
}

fn can_read_unchecked(schema: &ResolvedSchema, fl: &FieldLineage) -> bool {
    match &fl.mapping {
        FieldMapping::Discard => true,
        FieldMapping::PassThrough { target_name } => !target_is_lazy(schema, target_name),
        FieldMapping::Cast { .. } => false,
    }
}

// blastable fixed-width fields lead (each then sits at a constant offset), then
// seekable variable-width ones (so a seek's skip chain crosses only other
// seekable fields), then the rest. `seekable` is read from this version's own
// declaration, never the latest — sourcing it from the latest would relayout
// every historical version the moment a field is marked.
//
// Rank 0 is the historical fixed block; casts and lazy reads may still need
// checked decoding in that block. Optional is WireSize::Variable and so never
// rank 0; encode assigns presence-bit indices over all of `ordered` while
// decode/skip assign them over the non-blastable tail, and those agree only
// because of that. Keep it that way.
pub(crate) fn wire_rank(fl: &FieldLineage) -> u8 {
    if is_fixed_wire_field(fl) {
        0
    } else if fl.seekable {
        1
    } else {
        2
    }
}

// encode/decode/skip all use this same order, so the wire format stays consistent
pub(crate) fn ordered_wire_fields(vl: &VersionLineage) -> Vec<&FieldLineage> {
    let mut fields: Vec<&FieldLineage> = vl.fields.iter().collect();
    // stable, so declaration order survives within each rank
    fields.sort_by_key(|fl| wire_rank(fl));
    fields
}

pub fn generate(schema: &ResolvedSchema) -> String {
    generate_module(schema, true)
}

fn generate_module(schema: &ResolvedSchema, export_pluck: bool) -> String {
    let mut w = CodeWriter::default();

    w.line("// @generated — do not edit");
    w.line("// generated by pojoc");
    w.blank();
    w.line("pub mod runtime { pub use pojoc::*; }");
    w.line("use runtime::*;");
    if emit_serde() {
        w.line("// if this doesn't compile: `serde` (with the `derive` feature) must be a direct");
        w.line("// dependency, and the `pojoc`/`pojoc-build` `serde` feature must be enabled or");
        w.line("// disabled together");
        w.line("#[allow(unused_imports)]");
        w.line("use serde::{Serialize, Deserialize};");
    }
    w.blank();

    // types needing <'buf>: hold a lazy field or borrowed &'buf str, directly or transitively; type_info renders these via the thread-local set installed below
    // includes imported roots under their module-qualified names
    let infected = compute_lifetime_infected(schema);
    // nested generate calls for imports swap in their own set and restore ours on return
    let prev = set_infected(infected.clone());

    // types whose write_*/encode_vN must return PojocResult<()> because they carry a min:/max: constraint, same thread-local pattern as lifetime infection
    let constraint_infected = compute_constraint_infected(schema);
    let prev_constraint = set_constraint_infected(constraint_infected.clone());

    // types whose write_*/read_* threads the shared string-interning table because they carry an intern field
    let intern_infected = compute_intern_infected(schema);
    let prev_intern = set_intern_infected(intern_infected);

    // per-union-version (not blanket by name, see UNION_INTERN_INFECTED's doc)
    // whether that specific version's own variant set needs the intern table
    let union_intern_infected = compute_union_version_intern_infected(schema);
    let prev_union_intern = set_union_intern_infected(union_intern_infected);

    // write side's distinct criterion, see UNION_WRITE_INTERN_INFECTED's doc
    let union_write_intern_infected = compute_union_write_intern_infected(schema);
    let prev_union_write_intern = set_union_write_intern_infected(union_write_intern_infected);

    emit_imported_submodules(schema, &mut w);

    structs::emit_enums(schema, &mut w);
    structs::emit_structs(schema, &infected, &mut w);
    structs::emit_bitsets(schema, &mut w);
    structs::emit_unions(schema, &infected, &mut w);
    decode::emit_decode_functions(schema, &infected, &mut w);
    // after decode: reuses its read_*/skip_*/lazy_* helpers
    seek::emit_seek_functions(schema, &infected, export_pluck, &mut w);
    emit_dispatcher(
        schema,
        &infected,
        constraint_infected.contains(&schema.name_hint),
        &mut w,
    );
    w.blank();
    stream::emit_serve(
        schema,
        constraint_infected.contains(&schema.name_hint),
        &mut w,
    );
    w.blank();
    encode::emit_size_hint_helpers(schema, &mut w);
    encode::emit_size_hint_vn_functions(schema, &infected, &mut w);
    encode::emit_encode_helpers(schema, &mut w);
    encode::emit_encode_vn_functions(schema, &infected, &mut w);

    let result = w.finish();
    set_infected(prev);
    set_constraint_infected(prev_constraint);
    set_intern_infected(prev_intern);
    set_union_intern_infected(prev_union_intern);
    set_union_write_intern_infected(prev_union_write_intern);
    result
}

// per-TypeId (not by name — see UNION_INTERN_INFECTED's doc): whether this
// specific resolved union version's own variant set transitively uses intern.
// This is the read side's criterion — read_foo_vN only decodes discriminants
// that version's own historical variants could have produced. Note a nested
// union reached through a variant's payload recurses through
// type_ref_uses_intern's write-broadened Union arm rather than this same
// read-narrow one — a harmless over-approximation (an unused __table param,
// not a wire-format or correctness bug) for the rare case of a union payload
// struct that itself holds another union field.
fn compute_union_version_intern_infected(schema: &ResolvedSchema) -> HashSet<TypeId> {
    schema
        .unions
        .unions
        .iter()
        .filter(|(_, resolved)| {
            resolved.variants.iter().any(|v| {
                type_reaches_intern_table(
                    &schema.types,
                    &schema.unions,
                    &v.payload,
                    &mut HashSet::new(),
                )
            })
        })
        .map(|(id, _)| id.clone())
        .collect()
}

// write side's distinct criterion (see UNION_WRITE_INTERN_INFECTED's doc):
// write_foo_vN's match is exhaustive over the *latest* variant set (values of
// the one Rust enum shape), width-filtered the same way emit_union_writers
// filters which variants get a real write arm vs. a DiscriminantOverflow one.
fn compute_union_write_intern_infected(schema: &ResolvedSchema) -> HashSet<TypeId> {
    let latest_by_name = latest_by_name(&schema.unions.unions);

    schema
        .unions
        .unions
        .iter()
        .filter(|(id, resolved)| {
            let max_value = width_max_value(resolved.discriminant_width());
            let (_, latest) = latest_by_name[&id.name];
            latest
                .variants
                .iter()
                .filter(|v| v.discriminant <= max_value)
                .any(|v| {
                    type_reaches_intern_table(
                        &schema.types,
                        &schema.unions,
                        &v.payload,
                        &mut HashSet::new(),
                    )
                })
        })
        .map(|(id, _)| id.clone())
        .collect()
}

fn emit_dispatcher(
    schema: &ResolvedSchema,
    infected: &HashSet<String>,
    root_constrained: bool,
    w: &mut CodeWriter,
) {
    let name = &schema.name_hint;
    let latest = schema.lineage.latest_version;
    let needs_lifetime = infected.contains(name.as_str());

    let ref_lt = if needs_lifetime { "<'_>" } else { "" };
    w.line(&format!(
        "pub fn decode(buf: &[u8]) -> PojocResult<{name}{ref_lt}> {{"
    ));
    w.indent();
    w.line("let mut pos = 0;");
    w.line("let envelope = read_envelope(buf, &mut pos)?;");
    w.line("decode_payload(envelope.version, envelope.payload)");
    w.dedent();
    w.line("}");
    w.blank();

    w.line(&format!(
        "fn decode_payload(version: u64, payload: &[u8]) -> PojocResult<{name}{ref_lt}> {{"
    ));
    w.indent();
    w.line("let mut pos = 0;");
    w.line("match version {");
    w.indent();
    for vl in &schema.lineage.versions {
        let v = vl.version;
        w.line(&format!("{v} => decode_v{v}(payload, &mut pos),"));
    }
    w.line("v => Err(Error::UnsupportedVersion(v)),");
    w.dedent();
    w.line("}");
    w.dedent();
    w.line("}");
    w.blank();

    let encode_sig = if root_constrained {
        format!("pub fn encode(buf: &mut Vec<u8>, value: &{name}{ref_lt}) -> PojocResult<()> {{")
    } else {
        format!("pub fn encode(buf: &mut Vec<u8>, value: &{name}{ref_lt}) {{")
    };
    w.line(&encode_sig);
    w.indent();
    w.line(&format!("buf.reserve(size_hint_v{latest}(value));"));
    w.line(&format!(
        "let len_pos = write_envelope_header(buf, {latest});"
    ));
    w.line("let payload_start = buf.len();");
    if root_constrained {
        w.line(&format!("encode_v{latest}(buf, value)?;"));
    } else {
        w.line(&format!("encode_v{latest}(buf, value);"));
    }
    w.line("let payload_len = buf.len() - payload_start;");
    w.line("patch_envelope_length(buf, len_pos, payload_len);");
    if root_constrained {
        w.line("Ok(())");
    }
    w.dedent();
    w.line("}");
    w.blank();

    w.line(&format!(
        "pub fn encode_for_version(buf: &mut Vec<u8>, value: &{name}{ref_lt}, version: u64) -> PojocResult<()> {{"
    ));
    w.indent();
    w.line("let hint = match version {");
    w.indent();
    for vl in &schema.lineage.versions {
        let v = vl.version;
        w.line(&format!("{v} => size_hint_v{v}(value),"));
    }
    w.line("v => return Err(Error::UnsupportedVersion(v)),");
    w.dedent();
    w.line("};");
    w.line("buf.reserve(hint);");
    w.line("let len_pos = write_envelope_header(buf, version);");
    w.line("let payload_start = buf.len();");
    w.line("match version {");
    w.indent();
    for vl in &schema.lineage.versions {
        let v = vl.version;
        if root_constrained {
            w.line(&format!("{v} => encode_v{v}(buf, value)?,"));
        } else {
            w.line(&format!("{v} => encode_v{v}(buf, value),"));
        }
    }
    w.line("_ => unreachable!(),");
    w.dedent();
    w.line("}");
    w.line("let payload_len = buf.len() - payload_start;");
    w.line("patch_envelope_length(buf, len_pos, payload_len);");
    w.line("Ok(())");
    w.dedent();
    w.line("}");
    w.blank();

    w.line("pub fn supported_versions() -> &'static [u64] {");
    w.indent();
    let versions: Vec<String> = schema
        .lineage
        .versions
        .iter()
        .map(|vl| vl.version.to_string())
        .collect();
    w.line(&format!("&[{}]", versions.join(", ")));
    w.dedent();
    w.line("}");
}

fn emit_default(default: &DefaultValue, schema: &ResolvedSchema) -> String {
    match default {
        DefaultValue::None => "None".to_string(),
        DefaultValue::Bool(b) => b.to_string(),
        DefaultValue::Int(i) => i.to_string(),
        DefaultValue::Float(f) => {
            if f.fract() == 0.0 {
                format!("{f:.1}")
            } else {
                f.to_string()
            }
        }
        DefaultValue::Str(s) => format!("{s:?}"),
        DefaultValue::Array(els) => {
            if els.is_empty() {
                "PojocVec::new()".to_string()
            } else {
                let pushes = els
                    .iter()
                    .map(|e| format!("__v.push({});", emit_default(e, schema)))
                    .collect::<Vec<_>>()
                    .join(" ");
                format!("{{ let mut __v = PojocVec::new(); {pushes} __v }}")
            }
        }
        DefaultValue::Repeat(_) => unreachable!(
            "DefaultValue::Repeat should always get expanded into DefaultValue::Array before codegen."
        ),
        DefaultValue::Map(pairs) => {
            if pairs.is_empty() {
                "PojocMap::default()".to_string()
            } else {
                let inserts = pairs
                    .iter()
                    .map(|(k, v)| {
                        format!(
                            "__m.insert({}, {});",
                            emit_default(k, schema),
                            emit_default(v, schema)
                        )
                    })
                    .collect::<Vec<_>>()
                    .join(" ");
                format!("{{ let mut __m = PojocMap::default(); {inserts} __m }}")
            }
        }
        DefaultValue::Struct => "Default::default()".to_string(),
        DefaultValue::FixedBytes(bytes) => {
            if bytes.iter().all(|b| b.is_ascii_graphic() || *b == b' ') {
                let s = std::str::from_utf8(bytes).unwrap();
                format!("*b\"{s}\"")
            } else {
                let inner = bytes
                    .iter()
                    .map(|b| format!("0x{b:02x}u8"))
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("[{inner}]")
            }
        }
        DefaultValue::Tuple(elements) => {
            let inner = elements
                .iter()
                .map(|e| emit_default(e, schema))
                .collect::<Vec<_>>()
                .join(", ");
            format!("({inner})")
        }
        DefaultValue::EnumVariant { ty_name, variant } => {
            format!("{ty_name}::{variant}")
        }
        DefaultValue::BitsetLiteral { ty_name, kvs } => {
            if let Some((_, resolved_bitset)) = schema
                .bitsets
                .bitsets
                .iter()
                .filter(|(id, _)| id.name == *ty_name)
                .max_by_key(|(id, _)| id.version)
            {
                let computed_len = resolved_bitset.byte_width();
                let mut default_bytes = vec![0u8; computed_len];
                for (flag_name, flag_val) in kvs {
                    if *flag_val
                        && let Some(idx) = resolved_bitset
                            .variants
                            .iter()
                            .position(|v| v.name == *flag_name)
                    {
                        default_bytes[idx / 8] |= 1 << (idx % 8);
                    }
                }
                let inner = default_bytes
                    .iter()
                    .map(|b| format!("0x{b:02x}"))
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("{ty_name}([{inner}])")
            } else {
                format!("{ty_name}::default()")
            }
        }
    }
}

/// A field that (directly or nested) carries a borrowed `&'buf str` forces its
/// container to carry the `'buf` lifetime — exactly like a `lazy` field does.
/// Only meaningful under [`borrow_strings`]; named-type nesting is handled by
/// the propagation loop below via [`field_type_name`].
pub(crate) fn field_carries_borrowed_string(ty: &ResolvedTypeRef) -> bool {
    ty.any_node(
        &mut |t| matches!(t, ResolvedTypeRef::Scalar(id) if normalize_type(&id.name) == "string"),
    )
}

// whether a value of this type must borrow the input buffer, either directly or
// through a named type already known to. seek accessors need this per field,
// since a `seekable string` getter is <'buf> even when its root type is not.
pub(crate) fn field_is_lifetime_infected(
    ty: &ResolvedTypeRef,
    lazy: bool,
    infected: &HashSet<String>,
) -> bool {
    if lazy || field_carries_borrowed_string(ty) {
        return true;
    }
    let mut names = Vec::new();
    field_type_names(ty, &mut names);
    names.iter().any(|n| infected.contains(n))
}

fn compute_lifetime_infected(schema: &ResolvedSchema) -> HashSet<String> {
    let latest = latest_by_name(&schema.types.types);
    let latest_unions = latest_by_name(&schema.unions.unions);

    // imported roots first, so a field typed as one propagates infection through
    // the fixpoint below exactly like a locally declared type would
    let mut infected: HashSet<String> = schema
        .imports
        .iter()
        .filter(|(_, imported)| {
            compute_lifetime_infected(imported).contains(imported.name_hint.as_str())
        })
        .map(|(alias, imported)| format!("{}::{}", alias.to_snake_case(), imported.name_hint))
        .collect();

    infected.extend(
        latest
            .iter()
            .filter(|(_, (_, resolved))| {
                resolved
                    .fields
                    .iter()
                    .any(|f| f.lazy || field_carries_borrowed_string(&f.ty))
            })
            .map(|(name, _)| name.clone()),
    );

    infected.extend(
        latest_unions
            .iter()
            .filter(|(_, (_, resolved))| {
                resolved
                    .variants
                    .iter()
                    .any(|v| field_carries_borrowed_string(&v.payload))
            })
            .map(|(name, _)| name.clone()),
    );

    if schema
        .versions
        .last()
        .map(|v| {
            v.fields
                .iter()
                .any(|f| f.lazy || field_carries_borrowed_string(&f.ty))
        })
        .unwrap_or(false)
    {
        infected.insert(schema.name_hint.clone());
    }

    loop {
        let mut changed = false;
        for (name, (_, resolved)) in &latest {
            if infected.contains(name) {
                continue;
            }
            let newly_infected = resolved.fields.iter().any(|f| {
                let mut names = Vec::new();
                field_type_names(&f.ty, &mut names);
                names.iter().any(|n| infected.contains(n))
            });
            if newly_infected {
                infected.insert(name.clone());
                changed = true;
            }
        }
        for (name, (_, resolved)) in &latest_unions {
            if infected.contains(name) {
                continue;
            }
            let newly_infected = resolved.variants.iter().any(|v| {
                let mut names = Vec::new();
                field_type_names(&v.payload, &mut names);
                names.iter().any(|n| infected.contains(n))
            });
            if newly_infected {
                infected.insert(name.clone());
                changed = true;
            }
        }
        if !changed {
            break;
        }
    }

    // schema root isn't in `latest` (it's synthesized, not a `type` decl) so it skipped the propagation loop above; this catches transitive infection the seed check missed
    if !infected.contains(&schema.name_hint)
        && schema
            .versions
            .last()
            .map(|v| {
                v.fields.iter().any(|f| {
                    let mut names = Vec::new();
                    field_type_names(&f.ty, &mut names);
                    names.iter().any(|n| infected.contains(n))
                })
            })
            .unwrap_or(false)
    {
        infected.insert(schema.name_hint.clone());
    }

    infected
}

// true if ty is min:/max: constrained, unwrapping Optional/Boxed first since both still need a guard
fn field_is_constrained(ty: &ResolvedTypeRef) -> bool {
    match ty {
        ResolvedTypeRef::Constrained { .. } => true,
        ResolvedTypeRef::Optional(inner) | ResolvedTypeRef::Boxed(inner) => {
            field_is_constrained(inner)
        }
        _ => false,
    }
}

// names of types whose write_*/encode_vN must return PojocResult<()>, so the ? propagates from constrained fields up through containers
fn compute_constraint_infected(schema: &ResolvedSchema) -> HashSet<String> {
    let latest = latest_by_name(&schema.types.types);
    let latest_unions = latest_by_name(&schema.unions.unions);

    // imported roots first, same as compute_lifetime_infected: an imported
    // schema whose own encode is fallible makes every holder of it fallible too
    let mut infected: HashSet<String> = schema
        .imports
        .iter()
        .filter(|(_, imported)| {
            compute_constraint_infected(imported).contains(imported.name_hint.as_str())
        })
        .map(|(alias, imported)| format!("{}::{}", alias.to_snake_case(), imported.name_hint))
        .collect();

    infected.extend(
        latest
            .iter()
            .filter(|(_, (_, resolved))| {
                resolved.fields.iter().any(|f| field_is_constrained(&f.ty))
            })
            .map(|(name, _)| name.clone()),
    );

    // every union writer is unconditionally fallible: Unknown's discriminant
    // can always overflow this version's fixed width.
    infected.extend(latest_unions.keys().cloned());

    let root_seed = |fields: &[FieldIR]| fields.iter().any(|f| field_is_constrained(&f.ty));
    if schema
        .versions
        .last()
        .map(|v| root_seed(&v.fields))
        .unwrap_or(false)
    {
        infected.insert(schema.name_hint.clone());
    }

    loop {
        let mut changed = false;
        for (name, (_, resolved)) in &latest {
            if infected.contains(name) {
                continue;
            }
            let newly_infected = resolved.fields.iter().any(|f| {
                let mut names = Vec::new();
                field_type_names(&f.ty, &mut names);
                names.iter().any(|n| infected.contains(n))
            });
            if newly_infected {
                infected.insert(name.clone());
                changed = true;
            }
        }
        for (name, (_, resolved)) in &latest_unions {
            if infected.contains(name) {
                continue;
            }
            let newly_infected = resolved.variants.iter().any(|v| {
                let mut names = Vec::new();
                field_type_names(&v.payload, &mut names);
                names.iter().any(|n| infected.contains(n))
            });
            if newly_infected {
                infected.insert(name.clone());
                changed = true;
            }
        }
        if !changed {
            break;
        }
    }

    if !infected.contains(&schema.name_hint)
        && schema
            .versions
            .last()
            .map(|v| {
                v.fields.iter().any(|f| {
                    let mut names = Vec::new();
                    field_type_names(&f.ty, &mut names);
                    names.iter().any(|n| infected.contains(n))
                })
            })
            .unwrap_or(false)
    {
        infected.insert(schema.name_hint.clone());
    }

    infected
}

// emits a min/max bound-check guard if field is Constrained (directly or under one Optional); accessor must be a plain place expr, this fn adds any &/deref itself
pub(crate) fn emit_constraint_guard(field: &FieldIR, accessor: &str, w: &mut CodeWriter) {
    match &field.ty {
        ResolvedTypeRef::Constrained { inner, min, max } => {
            emit_bound_check(inner, accessor, false, &field.name, *min, *max, w);
        }
        ResolvedTypeRef::Optional(boxed) => {
            if let ResolvedTypeRef::Constrained { inner, min, max } = boxed.as_ref() {
                w.line(&format!("if let Some(__cval) = &{accessor} {{"));
                w.indent();
                emit_bound_check(inner, "__cval", true, &field.name, *min, *max, w);
                w.dedent();
                w.line("}");
            }
        }
        _ => {}
    }
}

// same as emit_constraint_guard, but for a union variant's payload rather than a struct field (no FieldIR to hang the label off, so the variant name is passed directly)
pub(crate) fn emit_union_variant_constraint_guard(
    payload: &ResolvedTypeRef,
    accessor: &str,
    variant_name: &str,
    w: &mut CodeWriter,
) {
    if let ResolvedTypeRef::Constrained { inner, min, max } = payload {
        emit_bound_check(inner, accessor, true, variant_name, *min, *max, w);
    }
}

#[allow(clippy::too_many_arguments)]
fn emit_bound_check(
    inner: &ResolvedTypeRef,
    accessor: &str,
    is_ref: bool,
    field_name: &str,
    min: Option<f64>,
    max: Option<f64>,
    w: &mut CodeWriter,
) {
    if min.is_none() && max.is_none() {
        return;
    }
    let is_count = matches!(
        inner,
        ResolvedTypeRef::Array(_) | ResolvedTypeRef::DeltaArray(_) | ResolvedTypeRef::Map(_, _)
    ) || matches!(inner, ResolvedTypeRef::Scalar(id) if normalize_type(&id.name) == "string");

    let value_expr = if is_count {
        format!("({accessor}.len() as f64)")
    } else if is_ref {
        format!("(*{accessor} as f64)")
    } else {
        format!("({accessor} as f64)")
    };

    let mut conds = Vec::new();
    if let Some(mn) = min {
        conds.push(format!("{value_expr} < {mn}f64"));
    }
    if let Some(mx) = max {
        conds.push(format!("{value_expr} > {mx}f64"));
    }
    let min_expr = min
        .map(|m| format!("Some({m}f64)"))
        .unwrap_or_else(|| "None".into());
    let max_expr = max
        .map(|m| format!("Some({m}f64)"))
        .unwrap_or_else(|| "None".into());

    w.line(&format!(
        "if {} {{ return Err(Error::ConstraintViolation {{ field: \"{field_name}\", min: {min_expr}, max: {max_expr} }}); }}",
        conds.join(" || ")
    ));
}

// names of types whose write_*/read_* must thread the shared intern table, same fixpoint shape as compute_constraint_infected
fn compute_intern_infected(schema: &ResolvedSchema) -> HashSet<String> {
    let latest = latest_by_name(&schema.types.types);
    let latest_unions = latest_by_name(&schema.unions.unions);

    let mut infected: HashSet<String> = latest
        .iter()
        .filter(|(_, (_, resolved))| resolved.fields.iter().any(|f| contains_interned(&f.ty)))
        .map(|(name, _)| name.clone())
        .collect();

    infected.extend(
        latest_unions
            .iter()
            .filter(|(_, (_, resolved))| {
                resolved
                    .variants
                    .iter()
                    .any(|v| contains_interned(&v.payload))
            })
            .map(|(name, _)| name.clone()),
    );

    if schema
        .versions
        .last()
        .map(|v| v.fields.iter().any(|f| contains_interned(&f.ty)))
        .unwrap_or(false)
    {
        infected.insert(schema.name_hint.clone());
    }

    loop {
        let mut changed = false;
        for (name, (_, resolved)) in &latest {
            if infected.contains(name) {
                continue;
            }
            let newly_infected = resolved.fields.iter().any(|f| {
                let mut names = Vec::new();
                field_type_names(&f.ty, &mut names);
                names.iter().any(|n| infected.contains(n))
            });
            if newly_infected {
                infected.insert(name.clone());
                changed = true;
            }
        }
        for (name, (_, resolved)) in &latest_unions {
            if infected.contains(name) {
                continue;
            }
            let newly_infected = resolved.variants.iter().any(|v| {
                let mut names = Vec::new();
                field_type_names(&v.payload, &mut names);
                names.iter().any(|n| infected.contains(n))
            });
            if newly_infected {
                infected.insert(name.clone());
                changed = true;
            }
        }
        if !changed {
            break;
        }
    }

    if !infected.contains(&schema.name_hint)
        && schema
            .versions
            .last()
            .map(|v| {
                v.fields.iter().any(|f| {
                    let mut names = Vec::new();
                    field_type_names(&f.ty, &mut names);
                    names.iter().any(|n| infected.contains(n))
                })
            })
            .unwrap_or(false)
    {
        infected.insert(schema.name_hint.clone());
    }

    infected
}

// whether version N's own historical fields ever touch interned data; gates the intern-table header per version so adding `intern` later doesn't retroactively break old wire bytes
pub(crate) fn version_uses_intern(schema: &ResolvedSchema, fields: &[FieldLineage]) -> bool {
    let mut visited = HashSet::new();
    fields.iter().any(|f| {
        type_reaches_intern_table(&schema.types, &schema.unions, &f.source_ty, &mut visited)
    })
}

// names of infected named types this field transitively references; direct borrowed strings are handled separately by field_carries_borrowed_string
fn field_type_names(ty: &ResolvedTypeRef, out: &mut Vec<String>) {
    ty.for_each_node(&mut |t| match t {
        ResolvedTypeRef::Scalar(id) if !is_primitive(&id.name) => out.push(id.name.clone()),
        ResolvedTypeRef::Union(id) => out.push(id.name.clone()),
        // an imported root is tracked under the module-qualified name type_info renders it as
        ResolvedTypeRef::ImportedSchema {
            alias, root_name, ..
        } => out.push(format!("{}::{root_name}", alias.to_snake_case())),
        _ => {}
    });
}

fn emit_imported_submodules(schema: &ResolvedSchema, w: &mut CodeWriter) {
    let mut aliases: Vec<&String> = schema.imports.keys().collect();
    aliases.sort();

    for alias in aliases {
        let imported = &schema.imports[alias];
        let module = alias.to_snake_case();
        let body = generate_module(imported, false);

        w.line(&format!("pub mod {module} {{"));
        w.indent();
        for line in body.lines() {
            if line.is_empty() {
                w.blank();
            } else {
                w.line(line);
            }
        }
        w.dedent();
        w.line("}");
        w.blank();
    }
}
